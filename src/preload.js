const { contextBridge, ipcRenderer } = require('electron');

contextBridge.exposeInMainWorld('zeroed', {
  getState: () => ipcRenderer.invoke('get-state'),
  onState: (cb) => ipcRenderer.on('state', (_e, s) => cb(s)),
  setActive: (cfg) => ipcRenderer.send('set-active', cfg),
  setVisible: (v) => ipcRenderer.send('set-visible', v),
  setDisplay: (i) => ipcRenderer.send('set-display', i),
  setHotkeys: (hk) => ipcRenderer.invoke('set-hotkeys', hk),
  savePreset: (name) => ipcRenderer.send('save-preset', name),
  deletePreset: (i) => ipcRenderer.send('delete-preset', i),
  exportCode: () => ipcRenderer.invoke('export-code'),
  importCode: (code) => ipcRenderer.invoke('import-code', code),
  exportFile: (all) => ipcRenderer.invoke('export-file', all),
  importFile: () => ipcRenderer.invoke('import-file'),
  setDetector: (d) => ipcRenderer.send('set-detector', d),
  onDetectorStatus: (cb) => ipcRenderer.on('detector-status', (_e, s) => cb(s)),
  analyzerReady: () => ipcRenderer.send('analyzer-ready'),
  analyzerStatus: (s) => ipcRenderer.send('analyzer-status', s),
  reportAlert: (a) => ipcRenderer.send('report-alert', a),
  onCaptureSource: (cb) => ipcRenderer.on('capture-source', (_e, id) => cb(id)),
  setGalleryUrl: (u) => ipcRenderer.invoke('set-gallery-url', u),
  galleryList: (q, sort) => ipcRenderer.invoke('gallery-list', q, sort),
  galleryAdd: (id, name) => ipcRenderer.invoke('gallery-add', id, name),
  galleryLike: (id) => ipcRenderer.invoke('gallery-like', id),
  galleryPublish: (name, author) => ipcRenderer.invoke('gallery-publish', name, author),
  listWindows: () => ipcRenderer.invoke('list-windows'),
  devUnlock: (pw) => ipcRenderer.invoke('dev-unlock', pw),
  devLock: () => ipcRenderer.send('dev-lock'),
  devSet: (d) => ipcRenderer.send('dev-set', d),
  devTestAlert: () => ipcRenderer.send('dev-test-alert'),
  debugFrame: (f) => ipcRenderer.send('debug-frame', f),
  onDebugFrame: (cb) => ipcRenderer.on('debug-frame', (_e, f) => cb(f)),
  onBadge: (cb) => ipcRenderer.on('badge', (_e, s) => cb(s)),
  profileCreate: (d) => ipcRenderer.invoke('profile-create', d),
  profileUpdate: (d) => ipcRenderer.invoke('profile-update', d),
  profileDelete: (id) => ipcRenderer.invoke('profile-delete', id),
  profileActivate: (id) => ipcRenderer.send('profile-activate', id),
  setProfileOpts: (d) => ipcRenderer.send('set-profile-opts', d),
  analyzerStats: (st) => ipcRenderer.send('analyzer-stats', st),
  endMatch: () => ipcRenderer.send('end-match'),
  onReport: (cb) => ipcRenderer.on('report', (_e, r) => cb(r)),
  closeReport: () => ipcRenderer.send('close-report'),
  setReportOpts: (d) => ipcRenderer.send('set-report-opts', d),
  showReport: (id) => ipcRenderer.send('show-report', id),
  clearReports: () => ipcRenderer.send('clear-reports'),
  pickImage: () => ipcRenderer.invoke('pick-image')
});
